<?php
/**
 * Creates single-use, time-limited WooCommerce coupons for clamped offers.
 *
 * @package Dev3\AiSmartCoupons
 */

namespace Dev3\AiSmartCoupons\Coupons;

use Dev3\AiSmartCoupons\Settings;

defined( 'ABSPATH' ) || exit;

/**
 * WC_Coupon wrapper.
 */
class Coupon_Factory {

	const META_GENERATED = '_dev3sc_generated';
	const META_SESSION   = '_dev3sc_session';
	const META_OFFER     = '_dev3sc_offer_id';

	/**
	 * Unique code: PREFIX-XXXXXXXX (unambiguous alphabet).
	 *
	 * @param string $prefix Prefix.
	 * @return string
	 */
	public static function unique_code( $prefix ) {
		$alphabet = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
		$prefix   = strtoupper( preg_replace( '/[^A-Za-z0-9]/', '', (string) $prefix ) );
		for ( $attempt = 0; $attempt < 10; $attempt++ ) {
			$suffix = '';
			for ( $i = 0; $i < 8; $i++ ) {
				$suffix .= $alphabet[ random_int( 0, strlen( $alphabet ) - 1 ) ];
			}
			$code = ( '' !== $prefix ? $prefix . '-' : '' ) . $suffix;
			if ( ! wc_get_coupon_id_by_code( $code ) ) {
				return $code;
			}
		}
		return ( '' !== $prefix ? $prefix . '-' : '' ) . strtoupper( wp_generate_password( 12, false ) );
	}

	/**
	 * Creates the coupon.
	 *
	 * @param array $offer        Clamped offer (type, amount, urgency_minutes, product_ids, excluded_ids).
	 * @param array $rules        Rules.
	 * @param array $ctx          { session_hash, email, subtotal, expires (unix) }.
	 * @return \WC_Coupon|\WP_Error
	 */
	public static function create( array $offer, array $rules, array $ctx ) {
		$rules  = array_merge( Settings::rule_defaults(), $rules );
		$code   = self::unique_code( $rules['code_prefix'] );
		$coupon = new \WC_Coupon();
		$coupon->set_code( $code );
		$coupon->set_description( __( 'Generated by DEV3 AI Smart Coupons for one shopping session. Single use.', 'dev3-ai-smart-coupons-for-woocommerce' ) );

		if ( 'free_shipping' === $offer['type'] ) {
			$coupon->set_discount_type( 'fixed_cart' );
			$coupon->set_amount( 0 );
			$coupon->set_free_shipping( true );
		} else {
			$coupon->set_discount_type( 'percent' === $offer['type'] ? 'percent' : 'fixed_cart' );
			$coupon->set_amount( wc_format_decimal( $offer['amount'], 2 ) );
			// The margin check was done for these exact products: the coupon only discounts them.
			$coupon->set_product_ids( array_map( 'intval', (array) $offer['product_ids'] ) );
		}

		$coupon->set_usage_limit( 1 );
		$coupon->set_usage_limit_per_user( 1 );
		$coupon->set_individual_use( ! empty( $rules['individual_use'] ) );
		$coupon->set_exclude_sale_items( ! empty( $rules['exclude_sale_items'] ) );
		$coupon->set_excluded_product_ids( array_values( array_unique( array_merge( array_map( 'intval', (array) $rules['excluded_product_ids'] ), array_map( 'intval', (array) $offer['excluded_ids'] ) ) ) ) );
		$coupon->set_excluded_product_categories( array_map( 'intval', (array) $rules['excluded_category_ids'] ) );

		// Minimum spend: the merchant floor, and for fixed amounts the cart value the margin was checked against.
		$minimum = (float) $rules['min_spend'];
		if ( 'fixed_cart' === $offer['type'] && ! empty( $ctx['subtotal'] ) ) {
			$minimum = max( $minimum, floor( (float) $ctx['subtotal'] ) );
		}
		if ( $minimum > 0 ) {
			$coupon->set_minimum_amount( wc_format_decimal( $minimum, 2 ) );
		}
		if ( ! empty( $ctx['email'] ) && is_email( $ctx['email'] ) ) {
			$coupon->set_email_restrictions( array( strtolower( $ctx['email'] ) ) );
		}
		$coupon->set_date_expires( (int) $ctx['expires'] );
		$coupon->update_meta_data( self::META_GENERATED, 1 );
		$coupon->update_meta_data( self::META_SESSION, (string) $ctx['session_hash'] );

		try {
			$coupon->save();
		} catch ( \Exception $e ) {
			return new \WP_Error( 'dev3sc_coupon_failed', $e->getMessage() );
		}
		if ( ! $coupon->get_id() ) {
			return new \WP_Error( 'dev3sc_coupon_failed', 'Coupon could not be saved.' );
		}
		return $coupon;
	}

	/**
	 * Whether a coupon was generated by this plugin.
	 *
	 * @param \WC_Coupon $coupon Coupon.
	 * @return bool
	 */
	public static function is_generated( $coupon ) {
		return $coupon instanceof \WC_Coupon && $coupon->get_id() && (bool) $coupon->get_meta( self::META_GENERATED );
	}
}
